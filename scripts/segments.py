# ---------------- 阶段判定 ----------------

def detect_segment(ans):
    p1 = (ans.get("P1") or "").strip().upper()
    p2 = (ans.get("P2") or "").strip().upper()
    # 处境优先于年龄：学生按探索期，重返职场按转型期
    if p2 == "A":
        return "early"
    if p2 == "F":
        return "senior" if p1 == "E" else "mid"
    if p1 in ("A", "B"):
        return "early"
    if p1 in ("D", "E"):
        return "senior"
    if p1 == "C":
        return "mid"
    # 没填年龄时看状态
    if p2 == "A":
        return "early"
    if p2 in ("D", "E"):
        return "senior"
    return "mid"


